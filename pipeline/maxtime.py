"""autodata_maxtime: the latest autodata row of each machine, collected while autodata is loaded.

One global DataFrame (MaxTimeTracker.frame) holds ONE row per machine. Every loaded chunk of autodata is
folded into it (update); when all windows are done, the frame is inserted into autodata_maxtime (write).
Nothing is re-read from the source or from the target.

Rule (the same as the old SQL Server trigger tr_autodata_maxtime and the live etl procedure):
  * only datatype 1 (cycle) and 2 (down) rows count
  * the row with the latest nd_time per machine wins (ties: later st_time)
  * an existing row in autodata_maxtime is replaced only when the new nd_time is not older,
    so a newer row written by the live ingest is never overwritten.
"""
import polars as pl
from psycopg import sql

KEY = "machine_iot_id"
ORDER = ["nd_time", "st_time"]
DATATYPES = (1, 2)
REQUIRED = [KEY, "datatype", "st_time", "nd_time"]
# every column of autodata_maxtime that autodata also has (id is generated by the target)
COLUMNS = [KEY, "component_iot_id", "operation_iot_id", "operator_iot_id", "datatype", "st_time", "nd_time",
           "component_interface_id", "operation_interface_id", "workorder_number", "serial_number",
           "heat_code", "supervisor_code"]


def latest_per_machine(rows : pl.DataFrame) -> pl.DataFrame:
    """The row with the latest (nd_time, st_time) of each machine, for datatype 1 and 2 only."""
    return (rows.filter(pl.col("datatype").is_in(DATATYPES) & pl.col(KEY).is_not_null() & pl.col("nd_time").is_not_null())
            .sort(ORDER, descending=True, nulls_last=True)
            .unique(subset=[KEY], keep="first", maintain_order=True))


class MaxTimeTracker:
    """The global DataFrame: one row per machine, always the latest row seen so far."""

    def __init__(self , schema : str = "production_core" , table : str = "autodata_maxtime"):
        self.schema, self.table = schema, table
        self.frame : pl.DataFrame | None = None

    def update(self , rows : pl.DataFrame) -> None:
        """Fold one chunk of loaded autodata rows (target column names) into the global frame."""
        if rows.height == 0 or any(c not in rows.columns for c in REQUIRED):
            return
        cols = [c for c in COLUMNS if c in rows.columns]
        chunk = latest_per_machine(rows.select(cols))
        if chunk.height == 0:
            return
        if self.frame is None:
            self.frame = chunk
        else:
            self.frame = latest_per_machine(pl.concat([self.frame, chunk], how="diagonal_relaxed"))

    def seed_from_target(self , conn , autodata_schema : str , autodata_table : str) -> int:
        """Resume: windows an earlier run completed are skipped, so their rows are not seen by update().
        Their rows are in the target, so read the latest row per machine from there. Returns the machines found."""
        cols = [c for c in COLUMNS]
        query = sql.SQL("SELECT DISTINCT ON ({key}) {cols} FROM {tbl} WHERE datatype IN (1, 2) AND {key} IS NOT NULL "
                        "ORDER BY {key}, nd_time DESC NULLS LAST, st_time DESC NULLS LAST").format(
            key=sql.Identifier(KEY), cols=sql.SQL(", ").join(sql.Identifier(c) for c in cols),
            tbl=sql.Identifier(autodata_schema, autodata_table))
        with conn.cursor() as cur:
            cur.execute(query)
            data = cur.fetchall()
        if data:
            self.update(pl.DataFrame(data, schema=cols, orient="row", infer_schema_length=None))
        return len(data)

    def write(self , conn) -> int:
        """Insert the frame into autodata_maxtime; a machine that is already there is updated unless its nd_time is newer.
        The caller owns the transaction. Returns the number of machines written."""
        if self.frame is None or self.frame.height == 0:
            return 0
        cols = [c for c in COLUMNS if c in self.frame.columns]
        tbl = sql.Identifier(self.schema, self.table)
        update_cols = [c for c in cols if c != KEY]
        query = sql.SQL(
            "INSERT INTO {tbl} ({cols}) VALUES ({vals}) ON CONFLICT ({key}) DO UPDATE SET {sets} "
            "WHERE {tbl}.nd_time IS NULL OR {tbl}.nd_time <= EXCLUDED.nd_time").format(
            tbl=tbl, cols=sql.SQL(", ").join(sql.Identifier(c) for c in cols),
            vals=sql.SQL(", ").join(sql.Placeholder() for _ in cols), key=sql.Identifier(KEY),
            sets=sql.SQL(", ").join(sql.SQL("{c} = EXCLUDED.{c}").format(c=sql.Identifier(c)) for c in update_cols))
        rows = list(self.frame.select(cols).iter_rows())
        with conn.cursor() as cur:
            cur.executemany(query, rows)
        return len(rows)


def tap(results , tracker : MaxTimeTracker):
    """Pass the transform results through unchanged, folding the rows that go to the load into the tracker."""
    for result in results:
        tracker.update(result.rows)
        yield result
